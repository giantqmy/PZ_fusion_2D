class DepthGate(nn.Module):
    """Fuse a Z-score-normalized depth branch into the SAFF lateral with a spatial gate."""

    def __init__(self, channels, depth_channel=0, depth_blocks=1, depth_stride=1):
        super().__init__()
        if depth_blocks < 1:
            raise ValueError(f"depth_blocks must be positive, got {depth_blocks}")
        if depth_stride < 1:
            raise ValueError(f"depth_stride must be positive, got {depth_stride}")
        depth_blocks = int(depth_blocks)
        depth_stride = int(depth_stride)

        hidden_channels = max(channels // 4, 8)
        self.depth_channel = depth_channel
        self.depth_stride = depth_stride
        # Match the visual branch: downsampling projection followed by ConvNeXt blocks.
        self.depth_encoder = nn.Sequential(
            nn.Conv2d(
                1,
                channels,
                kernel_size=depth_stride,
                stride=depth_stride,
                bias=False,
            ),
            nn.BatchNorm2d(channels),
            nn.SiLU(),
            *(ConvNeXtBlock(channels) for _ in range(depth_blocks)),
        )
        self.gate_mlp = nn.Sequential(
            nn.Conv2d(channels * 2, hidden_channels, kernel_size=1, bias=False),
            nn.BatchNorm2d(hidden_channels),
            nn.SiLU(),
            nn.Conv2d(hidden_channels, 1, kernel_size=1, bias=True),
        )

        # Start with a small depth residual while allowing the gate to learn freely.
        nn.init.zeros_(self.gate_mlp[-1].weight)
        nn.init.constant_(self.gate_mlp[-1].bias, -4.0)

    def forward(self, inputs):
        if not isinstance(inputs, (list, tuple)) or len(inputs) != 2:
            raise ValueError("DepthGate expects [saff_feature, raw_input]")
        saff_feature, raw_input = inputs
        if raw_input.ndim != 4:
            raise ValueError(f"DepthGate expects a BCHW raw input, got {raw_input.shape}")
        if not 0 <= self.depth_channel < raw_input.shape[1]:
            raise ValueError(
                f"depth_channel={self.depth_channel} is invalid for raw input with {raw_input.shape[1]} channels"
            )

        # The trainer/validator converts uint16(depth_m * 256) to a global
        # Z-score before model input. Zero remains the missing-depth value.
        depth = raw_input[:, self.depth_channel : self.depth_channel + 1]
        depth_feature = self.depth_encoder(depth)
        if depth_feature.shape[-2:] != saff_feature.shape[-2:]:
            raise ValueError(
                f"Depth feature size {depth_feature.shape[-2:]} does not match "
                f"visual feature size {saff_feature.shape[-2:]}; "
                f"check depth_stride={self.depth_stride}."
            )

        # The MLP produces one spatial weight per pixel; it is shared across channels.
        gate_input = torch.cat((saff_feature, depth_feature), dim=1)
        gate = torch.sigmoid(self.gate_mlp(gate_input))
        return saff_feature + gate * depth_feature


